-- The schema of the first Postgres release, translated from the SQLite one (src/db.ts before
-- the move). Applied once, at boot, by src/db.ts.
--
-- Conventions:
--   - Times are epoch milliseconds in bigint, as the pipeline and the API compute them.
--   - Every data row carries the workspace it belongs to. This release has one workspace
--     (ws_default, created at boot); indexes lead with workspace_id where queries filter by it.
--   - Ids the server generates are bigint identities; ids it mints itself (flg_, sec_, mdl_,
--     dec_) stay text.
--   - JSON whose text the API returns as parsed (event data, model reports, the featurizer
--     snapshot) is stored as text, so it comes back exactly as written. Plain id lists are jsonb.

CREATE TABLE workspaces (
  id         text   PRIMARY KEY,
  name       text   NOT NULL,
  created_at bigint NOT NULL
);

-- Raw request bodies, appended in the request path. status: new | done | failed
CREATE TABLE queue (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workspace_id text   NOT NULL REFERENCES workspaces(id),
  source       text   NOT NULL,
  received_at  bigint NOT NULL,
  body         bytea  NOT NULL,
  status       text   NOT NULL DEFAULT 'new'
);
CREATE INDEX queue_new ON queue (workspace_id, id) WHERE status = 'new';

-- Parsed events. decided once the decider has looked at it (or the classifier dropped it).
-- route: drop | jev | audit | novel | known | review | auto | classifier, or NULL when no triage ran.
CREATE TABLE events (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workspace_id text    NOT NULL REFERENCES workspaces(id),
  queue_id     bigint  NOT NULL,
  source       text    NOT NULL,
  received_at  bigint  NOT NULL,
  data         text    NOT NULL,
  external_id  text,
  type         text,
  group_key    text,
  decided      boolean NOT NULL DEFAULT false,
  -- Triage: the classifier's score, where the event went, its template and feature vector.
  score        double precision,
  route        text,
  template     text,
  features     bytea,
  user_key     text,
  -- Level and status class (e.g. e5): verdicts are cached per template and severity.
  severity     text,
  -- What a model running in shadow would have scored the event, and the route it would have
  -- taken (audits aside): `drop` means it would not have reached Jev. shadow_model is that
  -- model's trained_at; fv the featurizer version of `features`.
  shadow_score double precision,
  shadow_route text,
  shadow_model text,
  fv           integer
);
CREATE INDEX events_pending ON events (workspace_id, id) WHERE NOT decided;
CREATE INDEX events_received ON events (workspace_id, received_at);
CREATE INDEX events_source_received ON events (workspace_id, source, received_at);
CREATE INDEX events_user ON events (workspace_id, user_key) WHERE user_key IS NOT NULL;

-- The escalation queue: open -> acknowledged -> resolved, or confirmed / false_positive by feedback.
CREATE TABLE flags (
  id           text   PRIMARY KEY,
  workspace_id text   NOT NULL REFERENCES workspaces(id),
  created_at   bigint NOT NULL,
  reason       text   NOT NULL,
  severity     text   NOT NULL,
  event_ids    jsonb  NOT NULL,
  decider      text   NOT NULL,
  status       text   NOT NULL DEFAULT 'open',
  updated_at   bigint,
  event_count  integer,
  users        jsonb,
  note         text
);
CREATE INDEX flags_created ON flags (workspace_id, created_at);
CREATE INDEX flags_status ON flags (workspace_id, status, created_at);

-- Outbox: one row per (flag, action). status: pending | ok | failed. A delivery being run is
-- claimed by moving next_attempt_at forward (see worker.ts), so it is never due twice at once.
CREATE TABLE deliveries (
  flag_id         text    NOT NULL REFERENCES flags(id) ON DELETE CASCADE,
  workspace_id    text    NOT NULL REFERENCES workspaces(id),
  action          text    NOT NULL,
  status          text    NOT NULL DEFAULT 'pending',
  attempts        integer NOT NULL DEFAULT 0,
  next_attempt_at bigint  NOT NULL,
  last_error      text,
  updated_at      bigint  NOT NULL,
  PRIMARY KEY (flag_id, action)
);
CREATE INDEX deliveries_due ON deliveries (workspace_id, next_attempt_at) WHERE status = 'pending';

-- Training labels for the classifier: what Jev or a person decided about an event, with the
-- feature vector the classifier saw. Copied out of events so labels outlive retention.
-- source: jev | human. A human label always replaces a Jev label, never the other way round.
-- Imported history gets negative event ids, so it never collides with real events.
CREATE TABLE labels (
  workspace_id       text    NOT NULL REFERENCES workspaces(id),
  event_id           bigint  NOT NULL,
  y                  integer NOT NULL,
  source             text    NOT NULL,
  route              text,
  score              double precision,
  features           bytea   NOT NULL,
  featurizer_version integer NOT NULL,
  event_source       text    NOT NULL,
  received_at        bigint  NOT NULL,
  data               text    NOT NULL,
  note               text,
  created_at         bigint  NOT NULL,
  -- The labelled event's template, so a kind of event someone escalated keeps reaching Jev.
  template           text,
  -- How the label came about (threshold | audit | novel | known | follower | human | import),
  -- its training weight, and the decider call it came from.
  provenance         text,
  weight             double precision,
  decision_id        text,
  -- Severity and context of the event when it was judged, so earned suppression and
  -- escalation memory can be rebuilt exactly after a restart (routing.ts).
  severity           text,
  ctx_rate           double precision,
  ctx_service_errors double precision,
  PRIMARY KEY (workspace_id, event_id)
);
CREATE INDEX labels_created ON labels (workspace_id, created_at);
CREATE INDEX labels_template ON labels (workspace_id, template) WHERE template IS NOT NULL;

-- Every classifier cloudfriend trained or loaded. status: active | shadow | rejected | retired | skipped | failed
CREATE TABLE models (
  id           text    PRIMARY KEY,
  workspace_id text    NOT NULL REFERENCES workspaces(id),
  created_at   bigint  NOT NULL,
  path         text    NOT NULL,
  status       text    NOT NULL,
  labels       integer NOT NULL DEFAULT 0,
  report       text    NOT NULL
);
CREATE INDEX models_created ON models (workspace_id, created_at);

-- Every decider call that produced labels: the exact prompt and raw reply, for audit.
CREATE TABLE decisions (
  id           text   PRIMARY KEY,
  workspace_id text   NOT NULL REFERENCES workspaces(id),
  created_at   bigint NOT NULL,
  decider      text   NOT NULL,
  model        text,
  prompt       text,
  response     text,
  event_ids    jsonb  NOT NULL
);
CREATE INDEX decisions_created ON decisions (workspace_id, created_at);

-- The featurizer's template history, saved every minute and on shutdown so a restart doesn't
-- make every message look new.
CREATE TABLE snapshots (
  workspace_id text   PRIMARY KEY REFERENCES workspaces(id),
  featurizer   text   NOT NULL,
  updated_at   bigint NOT NULL
);

-- Ingest secrets: only a SHA-256 hash is stored.
CREATE TABLE secrets (
  id           text   PRIMARY KEY,
  workspace_id text   NOT NULL REFERENCES workspaces(id),
  name         text   NOT NULL,
  source       text,
  hash         text   NOT NULL UNIQUE,
  prefix       text   NOT NULL,
  created_at   bigint NOT NULL,
  last_used_at bigint,
  revoked_at   bigint
);
CREATE INDEX secrets_workspace ON secrets (workspace_id, created_at);
